CREATE TABLE IF NOT EXISTS GameServer (
	id VARCHAR(36) PRIMARY KEY,
	gamePort INTEGER NOT NULL UNIQUE CHECK (gamePort BETWEEN 1 AND 65535),
	-- Null for server types without RCON, such as Bedrock and Hytale
	rconPort INTEGER UNIQUE CHECK (rconPort BETWEEN 1 AND 65535)
);

CREATE TABLE IF NOT EXISTS ProviderToken (
	name VARCHAR(255) PRIMARY KEY,
	token VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS VpnType (
	id VARCHAR(255) PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS Vpn (
	id VARCHAR(255) PRIMARY KEY,
	vpnTypeId VARCHAR(255) NOT NULL REFERENCES VpnType (id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS IPs (
	gameServerId VARCHAR(36) NOT NULL REFERENCES GameServer (id) ON DELETE CASCADE,
	vpnId VARCHAR(255) NOT NULL REFERENCES Vpn (id) ON DELETE RESTRICT,
	PRIMARY KEY (gameServerId, vpnId)
);

CREATE INDEX IF NOT EXISTS IPs_vpnId ON IPs (vpnId);
